#ifndef TUSB9261_RDX_SWITCH_TEST_H
#define TUSB9261_RDX_SWITCH_TEST_H

#include <stdint.h>

#define MMIO32(address) (*(volatile uint32_t *)(address))

/* System and clock-control registers retained from the TI TUSB9261 source. */
#define SCB_VTOR MMIO32(0xE000ED08UL)
#define SYSTEM_CTRL MMIO32(0xE000ED10UL)
#define PCR_PPROTCLR0 MMIO32(0xFFFFE040UL)
#define PCR_PSPWRDWNCLR0 MMIO32(0xFFFFE0A0UL)
#define PCR_PSPWRDWNCLR1 MMIO32(0xFFFFE0A4UL)
#define PCR_PSPWRDWNCLR2 MMIO32(0xFFFFE0A8UL)
#define PCR_PSPWRDWNCLR3 MMIO32(0xFFFFE0ACUL)
#define CLKCNTL MMIO32(0xFFFFFFD0UL)

/* The front bicolor LED uses GIO port zero. */
#define GIOGCR0 MMIO32(0xFFF7BC00UL)
#define GIODIR0 MMIO32(0xFFF7BC34UL)
#define GIOIN0 MMIO32(0xFFF7BC38UL)
#define GIOOUT0 MMIO32(0xFFF7BC3CUL)
#define GIOPULDIS0 MMIO32(0xFFF7BC4CUL)

#define FRONT_GREEN_LED_MASK (1UL << 7)
#define FRONT_AMBER_LED_MASK (1UL << 6)

/* SPI register addresses and values retained from the production firmware. */
#define SPI_GCR0 MMIO32(0xFFF7F800UL)
#define SPI_GCR1 MMIO32(0xFFF7F804UL)
#define SPI_LVL MMIO32(0xFFF7F80CUL)
#define SPI_FLG MMIO32(0xFFF7F810UL)
#define SPI_PC0 MMIO32(0xFFF7F814UL)
#define SPI_PC1 MMIO32(0xFFF7F818UL)
#define SPI_PC7 MMIO32(0xFFF7F830UL)
#define SPI_DAT1 MMIO32(0xFFF7F83CUL)
#define SPI_BUF MMIO32(0xFFF7F840UL)
#define SPI_DELAY MMIO32(0xFFF7F848UL)
#define SPI_DEF MMIO32(0xFFF7F84CUL)
#define SPI_FMT0 MMIO32(0xFFF7F850UL)
#define SPI_FMT1 MMIO32(0xFFF7F854UL)

#define SPI_MASTER_INTERNAL_CLOCK 3UL
#define SPI_ENABLE_BIT 0x01000000UL
#define SPI_FUNCTION_MASK 0x00000E03UL
#define SPI_DIRECTION_MASK 0x00000601UL
#define SPI_DELAY_CONFIGURATION 0x02020000UL
#define SPI_DEFAULT_CHIP_SELECTS 3UL
#define SPI_PULL_DISABLE_CONFIGURATION 4UL
#define SPI_FORMAT_ZERO_CONFIGURATION 0x01010308UL
#define SPI_FORMAT_ONE_CONFIGURATION 0x01002408UL
#define SPI_TX_READY_FLAG 0x00000200UL
#define SPI_RX_READY_FLAG 0x00000100UL
#define SPI_RX_ERROR_FLAG 0x00000010UL
#define SPI_WAIT_LIMIT 1000000UL

/* Recovered MCP3008 transaction words and production thresholds. */
#define MCP3008_START_WORD 0x11050001UL
#define MCP3008_CHANNEL_WORD 0x11050080UL
#define MCP3008_FINISH_WORD 0x01050000UL
#define LOCK_SLIDER_ADC_CHANNEL 4UL
#define LOCK_SLIDER_ADC_THRESHOLD 650UL

void switch_test_system_init(void);
void main(void);

#endif /* TUSB9261_RDX_SWITCH_TEST_H */
