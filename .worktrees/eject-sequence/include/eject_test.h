#ifndef TUSB9261_RDX_EJECT_TEST_H
#define TUSB9261_RDX_EJECT_TEST_H

#include <stdint.h>

#define MMIO32(address) (*(volatile uint32_t *)(address))

/* System and clock-control registers retained from the TI TUSB9261 source. */
#define SCB_VTOR MMIO32(0xE000ED08UL)
#define SYSTEM_CTRL MMIO32(0xE000ED10UL)
#define PCR_PPROTCLR0 MMIO32(0xFFFFE040UL)
#define PCR_PSPWRDWNCLR0 MMIO32(0xFFFFE0A0UL)
#define PCR_PSPWRDWNCLR1 MMIO32(0xFFFFE0A4UL)
#define PCR_PSPWRDWNCLR2 MMIO32(0xFFFFE0A8UL)
#define PCR_PSPWRDWNCLR3 MMIO32(0xFFFFE0ACUL)
#define CLKCNTL MMIO32(0xFFFFFFD0UL)
#define DEVICE_ID MMIO32(0xFFFFFFF0UL)

/* The original RDX logical-I/O table maps button input 1 to GPIO1. */
#define GIOGCR0 MMIO32(0xFFF7BC00UL)
#define GIODIR0 MMIO32(0xFFF7BC34UL)
#define GIOIN0 MMIO32(0xFFF7BC38UL)
#define GIOOUT0 MMIO32(0xFFF7BC3CUL)
#define GIOPULDIS0 MMIO32(0xFFF7BC4CUL)

/* RTI counter zero supplies microseconds and counter one milliseconds. */
#define RTIGCTRL MMIO32(0xFFFFFC00UL)
#define RTIFRC0 MMIO32(0xFFFFFC10UL)
#define RTIUC0 MMIO32(0xFFFFFC14UL)
#define RTICPUC0 MMIO32(0xFFFFFC18UL)
#define RTIFRC1 MMIO32(0xFFFFFC30UL)
#define RTIUC1 MMIO32(0xFFFFFC34UL)
#define RTICPUC1 MMIO32(0xFFFFFC38UL)
#define RTISETINT MMIO32(0xFFFFFC80UL)

/* Logical output 13 selects PWM1 in the original RDX payload. */
#define PWM1_PCR MMIO32(0xFFF78C04UL)
#define PWM1_CFG MMIO32(0xFFF78C08UL)
#define PWM1_START MMIO32(0xFFF78C0CUL)
#define PWM1_PER MMIO32(0xFFF78C14UL)
#define PWM1_PH1D MMIO32(0xFFF78C18UL)

#define EJECT_BUTTON_MASK (1UL << 1)
#define EJECT_BUTTON_ASSERTED 0UL
#define MOTOR_CONTROL_MASK (1UL << 3)
#define MOTOR_DEAD_TIME_US 50UL
#define MOTOR_RUN_TIME_MS 2000UL
#define MOTOR_PWM_PERIOD_US 50UL

#define PWM_PCR_FREE_RUN_BIT 1UL
#define PWM_CFG_PHASE1_OUTPUT_HIGH 0x10UL
#define PWM_CFG_MODE_CONTINUOUS 2UL
#define PWM_CFG_MOTOR_BITS 0x23UL
#define PWM_START_BIT 1UL

void eject_test_system_init(void);
void main(void);

#endif /* TUSB9261_RDX_EJECT_TEST_H */
